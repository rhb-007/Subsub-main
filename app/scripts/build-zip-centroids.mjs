// Writes shared/zipcentroids.js from the us-zips package: the center of every
// ZIP Code Tabulation Area the US Census Bureau publishes (2020 ZCTAs), which is
// what "every ZIP within 15 miles of Tacoma" is worked out from.
//
// Generated, never hand-edited, for the reason npm run licensing is: a digit
// typed wrong is a wrong ZIP in somebody's market. Re-run when us-zips moves.
//
//   node scripts/build-zip-centroids.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const zips = require("us-zips");
const pkg = require("us-zips/package.json");
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "shared", "zipcentroids.js");

// zip:lat:lng, the angles in thousandths of a degree (about 100 yards), sorted
// by ZIP. One string, parsed the first time somebody asks.
const rows = Object.keys(zips).filter((z) => /^\d{5}$/.test(z)).sort().map((z) => {
  const { latitude, longitude } = zips[z];
  return `${z}:${Math.round(latitude * 1000)}:${Math.round(longitude * 1000)}`;
});
writeFileSync(out, `// GENERATED by scripts/build-zip-centroids.mjs from us-zips ${pkg.version}
// (US Census Bureau ZIP Code Tabulation Areas). Do not edit by hand.
// zip:lat:lng, the angles in thousandths of a degree, sorted by ZIP.
export const ZIP_SOURCE = "US Census Bureau ZCTAs, us-zips ${pkg.version}";
export const ZIP_COUNT = ${rows.length};
export const ZIP_CENTROIDS = "${rows.join(",")}";
`);
console.log(`wrote ${rows.length} ZIPs to ${out}`);
