// Writes shared/zipcities.js: the town each ZIP belongs to, from the zipcodes
// package (its US data is the GeoNames postal-code file). Read as text and
// JSON-parsed, never required, so nothing in the package runs here.
//
// Generated, never hand-edited, for the reason npm run zips is: a town typed
// wrong is a wrong town in somebody's market. Re-run when zipcodes moves.
//
//   node scripts/build-zip-cities.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("zipcodes/package.json"));
const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
const src = readFileSync(join(pkgDir, "lib", "codes.js"), "utf8");
const line = src.split("\n").find((l) => l.startsWith("exports.codes = "));
if (!line) throw new Error("zipcodes: exports.codes line not found");
const codes = JSON.parse(line.slice("exports.codes = ".length).replace(/;\s*$/, ""));
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "shared", "zipcities.js");

// Towns once each ("City|ST"), then zip:index sorted by ZIP, so the file is
// about a third of the size of writing the town against every ZIP.
const towns = [];
const index = new Map();
const rows = [];
for (const z of Object.keys(codes).filter((k) => /^\d{5}$/.test(k)).sort()) {
  const r = codes[z];
  if (r.country !== "US" || !r.city || !/^[A-Z]{2}$/.test(r.state || "")) continue;
  const city = String(r.city).trim().replace(/\s+/g, " ").replace(/[|,:]/g, " ");
  const key = `${city}|${r.state}`;
  if (!index.has(key)) { index.set(key, towns.length); towns.push(key); }
  rows.push(`${z}:${index.get(key).toString(36)}`);
}
writeFileSync(out, `// GENERATED by scripts/build-zip-cities.mjs from zipcodes ${pkg.version}
// (GeoNames US postal codes). Do not edit by hand.
// ZIP_TOWNS is "City|ST" joined by commas; ZIP_TOWN_OF is zip:index (base 36).
export const ZIP_TOWN_SOURCE = "GeoNames US postal codes, zipcodes ${pkg.version}";
export const ZIP_TOWN_COUNT = ${rows.length};
export const ZIP_TOWNS = ${JSON.stringify(towns.join(","))};
export const ZIP_TOWN_OF = "${rows.join(",")}";
`);
console.log(`wrote ${rows.length} ZIPs and ${towns.length} towns to ${out}`);
