// Draws the images an Apple Wallet pass carries and writes them, base64, into
// worker/walletimages.js. A Worker cannot rasterize an SVG, so this runs here
// with sharp and the module is committed; run `npm run wallet:images` again
// only when the mark changes.
//
// The paths are SubSub's own mark, the three shapes in favicon.svg. icon.png is
// what iOS shows on a lock-screen notice, so it is the gold mark on forest;
// logo.png sits on the pass itself, which is already forest, so it is the mark
// alone with a clear background.
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const MARK = [
  "M124.35,80.05l-78,36.53c-1.99,0.93-4.27-0.52-4.27-2.72V98.92c0-2.66,1.54-5.07,3.94-6.2L98.82,68c2.61-1.22,5.6-1.31,8.28-0.25l17.09,6.78C126.63,75.51,126.73,78.93,124.35,80.05z",
  "M43.81,156.95l78-36.53c1.99-0.93,4.27,0.52,4.27,2.72v14.93c0,2.66-1.54,5.07-3.94,6.2L69.34,169c-2.61,1.22-5.6,1.31-8.28,0.25l-17.09-6.78C41.53,161.49,41.43,158.07,43.81,156.95z",
  "M124.51,111.55l-57.06,26.43c-2.31,1.09-4.76,0.85-7.27-0.19l-16.4-6.7c-2.37-0.98-2.45-4.42-0.13-5.52l57.16-26.43c2.7-1.15,4.5-1.1,7.52-0.06l16.05,6.94C126.75,107.01,126.83,110.45,124.51,111.55z",
];
const GOLD = "#E39B32";
const FOREST = "#103528";
const paths = MARK.map((d) => `<path d="${d}" fill="${GOLD}"/>`).join("");

// The icon: a square, the mark centered at about 70% of it.
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160">
<rect width="160" height="160" fill="${FOREST}"/>
<g transform="translate(80 80) scale(0.85) translate(-84 -118)">${paths}</g></svg>`;
// The logo: just the mark, tight to its own box.
const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="32 58 104 120">${paths}</svg>`;

const out = {};
for (const [name, size] of [["icon.png", 29], ["icon@2x.png", 58], ["icon@3x.png", 87]]) {
  out[name] = await sharp(Buffer.from(iconSvg), { density: 600 }).resize(size, size).png().toBuffer();
}
for (const [name, h] of [["logo.png", 50], ["logo@2x.png", 100], ["logo@3x.png", 150]]) {
  out[name] = await sharp(Buffer.from(logoSvg), { density: 600 }).resize({ height: h }).png().toBuffer();
}

const lines = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v.toString("base64"))},`);
writeFileSync(new URL("../worker/walletimages.js", import.meta.url),
  `// Generated by scripts/build-wallet-images.mjs. Do not edit by hand.\n` +
  `export const WALLET_IMAGES = {\n${lines.join("\n")}\n};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k} ${v.length}B`).join("\n"));
